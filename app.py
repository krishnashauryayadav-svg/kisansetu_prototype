def render_mandi_analytics(df: pd.DataFrame) -> None:
    st.title("Mandi Analytics")
    st.caption("Government mandi price benchmarking, ONDC price comparison & farmer profit impact")

    # Use the live (session) inventory so entries logged in the VLE Dashboard
    # show up here too.
    working_df = st.session_state.get("inventory", df)

    if working_df.empty:
        st.info("No inventory data loaded yet.")
        return

    # ------------------------------------------------------------------
    # Derive an ONDC listing price where one isn't already stored.
    # Rows graded via the VLE Dashboard already carry an ONDC-adjusted
    # Current_Mandi_Price; for a clean side-by-side comparison here we
    # keep the original mandi price separate and derive the ONDC price
    # as mandi price + 10%, consistent with the VLE grading logic.
    # ------------------------------------------------------------------
    analytics_df = working_df.copy()
    analytics_df["ONDC_Listing_Price"] = round(analytics_df["Current_Mandi_Price"] * 1.10, 2)

    # ------------------------------------------------------------------
    # Top 3 crops by total listed quantity (i.e. most-traded on the platform)
    # ------------------------------------------------------------------
    top_crops = (
        analytics_df.groupby("Crop_Type")["Quantity_KG"]
        .sum()
        .sort_values(ascending=False)
        .head(3)
        .index.tolist()
    )

    st.subheader("📊 Mandi Price vs ONDC Listing Price — Top 3 Crops")
    st.caption(f"Ranked by total listed volume: {', '.join(top_crops)}")

    comparison_df = (
        analytics_df[analytics_df["Crop_Type"].isin(top_crops)]
        .groupby("Crop_Type")[["Current_Mandi_Price", "ONDC_Listing_Price"]]
        .mean()
        .reset_index()
        .rename(
            columns={
                "Current_Mandi_Price": "Avg Mandi Price",
                "ONDC_Listing_Price": "Avg ONDC Listing Price",
            }
        )
    )

    # Reshape to long format for a grouped/clustered bar chart in Altair
    chart_df = comparison_df.melt(
        id_vars="Crop_Type",
        value_vars=["Avg Mandi Price", "Avg ONDC Listing Price"],
        var_name="Price Type",
        value_name="Price (₹/kg)",
    )

    grouped_bar = (
        alt.Chart(chart_df)
        .mark_bar()
        .encode(
            x=alt.X("Crop_Type:N", title="Crop", axis=alt.Axis(labelAngle=0)),
            y=alt.Y("Price (₹/kg):Q", title="Price (₹/kg)"),
            color=alt.Color(
                "Price Type:N",
                scale=alt.Scale(
                    domain=["Avg ONDC Listing Price","Avg Mandi Price"],
                    range=[ "#94a3b8","#16a34a"],
                ),
            ),
            xOffset="Price Type:N",
            tooltip=["Crop_Type", "Price Type", alt.Tooltip("Price (₹/kg):Q", format=".2f")],
        )
        .properties(height=380)
    )

    st.altair_chart(grouped_bar, use_container_width=True)

    st.divider()

    # ------------------------------------------------------------------
    # Farmer Profit Impact metric card
    # ------------------------------------------------------------------
    st.subheader("💰 Farmer Profit Impact")

    total_mandi_value = (analytics_df["Current_Mandi_Price"] * analytics_df["Quantity_KG"]).sum()
    simulated_kisansetu_value = total_mandi_value * 1.15  # simulated 15% uplift from bypassing middlemen
    profit_gain = simulated_kisansetu_value - total_mandi_value

    m_col1, m_col2, m_col3 = st.columns(3)
    m_col1.metric(
        "Traditional Channel Value (est.)",
        f"₹{total_mandi_value:,.0f}",
    )
    m_col2.metric(
        "KisanSetu Net Value (Simulated)",
        f"₹{simulated_kisansetu_value:,.0f}",
        delta="+15% vs middlemen channel",
    )
    m_col3.metric(
        "Additional Farmer Earnings",
        f"₹{profit_gain:,.0f}",
    )

    st.caption(
        "Simulated estimate: assumes a 15% average net-earnings uplift for farmers from "
        "direct ONDC market access versus traditional intermediary-based selling. "
        "Based on current session inventory value (Σ Quantity × Mandi Price)."
    )

    st.divider()

    # ------------------------------------------------------------------
    # Existing crop-level browsing tools
    # ------------------------------------------------------------------
    crop_filter = st.selectbox(
        "Select Crop Type", options=["All"] + sorted(analytics_df["Crop_Type"].unique().tolist())
    )
    filtered = analytics_df if crop_filter == "All" else analytics_df[analytics_df["Crop_Type"] == crop_filter]

    st.subheader("Average Mandi Price by Crop")
    price_by_crop = filtered.groupby("Crop_Type")["Current_Mandi_Price"].mean().sort_values(ascending=False)
    st.bar_chart(price_by_crop)

    st.subheader("Price Distribution Table")
    st.dataframe(filtered, use_container_width=True)

