def get_reference_mandi_price(df: pd.DataFrame, crop: str) -> float:
    """
    Looks up a reference mandi price for a crop from existing inventory data
    (average of current listings for that crop). Falls back to the overall
    average price if the crop has no prior listings.
    """
    crop_rows = df[df["Crop_Type"] == crop]
    if not crop_rows.empty:
        return round(crop_rows["Current_Mandi_Price"].mean(), 2)
    if not df.empty:
        return round(df["Current_Mandi_Price"].mean(), 2)
    return 20.00  # generic fallback if no data exists at all


def render_vle_dashboard(df: pd.DataFrame) -> None:
    st.title("VLE Dashboard")
    st.caption("Village-level operator view — onboarding, weighing & catalogue creation")

    working_df = st.session_state["inventory"]

    if working_df.empty:
        st.info("No inventory data loaded yet.")
        return

    col1, col2, col3 = st.columns(3)
    col1.metric("Total Listings", len(working_df))
    col2.metric("Total Quantity (KG)", f"{working_df['Quantity_KG'].sum():,}")
    col3.metric("Active Hubs", working_df["Hub_Location"].nunique())

    st.divider()

    # ----------------------------------------------------------------------
    # Log New Produce form
    # ----------------------------------------------------------------------
    st.subheader("📝 Log New Produce")

    crop_options = sorted(working_df["Crop_Type"].unique().tolist())
    hub_options = sorted(working_df["Hub_Location"].unique().tolist())

    with st.form("log_produce_form", clear_on_submit=True):
        f_col1, f_col2, f_col3 = st.columns(3)
        farmer_name = f_col1.text_input("Farmer Name")
        crop_type = f_col2.selectbox("Crop", options=crop_options)
        weight_kg = f_col3.number_input("Weight (KG)", min_value=1, max_value=5000, value=100, step=10)

        hub_location = st.selectbox("Hub Location", options=hub_options)

        submitted = st.form_submit_button("Log Produce")

        if submitted:
            if not farmer_name.strip():
                st.warning("Please enter a farmer name before logging produce.")
            else:
                st.session_state["pending_entry"] = {
                    "Farmer_Name": farmer_name.strip(),
                    "Crop_Type": crop_type,
                    "Quantity_KG": int(weight_kg),
                    "Hub_Location": hub_location,
                }

    # ----------------------------------------------------------------------
    # Simulate AI Grading
    # ----------------------------------------------------------------------
    pending = st.session_state["pending_entry"]

    if pending is not None:
        st.info(
            f"Pending entry: **{pending['Farmer_Name']}** — {pending['Quantity_KG']} kg "
            f"of **{pending['Crop_Type']}** @ {pending['Hub_Location']}. "
            "Run AI grading to assign a quality grade and suggested listing price."
        )

        if st.button("🤖 Simulate AI Grading"):
            with st.spinner("Running AI quality-grading model..."):
                time.sleep(2)

                grade = random.choice(["A", "B", "C"])
                mandi_price = get_reference_mandi_price(working_df, pending["Crop_Type"])
                suggested_price = round(mandi_price * 1.10, 2)  # +10% over mandi price

                new_entry = {
                    "Farmer_Name": pending["Farmer_Name"],
                    "Crop_Type": pending["Crop_Type"],
                    "Quantity_KG": pending["Quantity_KG"],
                    "Grade": grade,
                    "Current_Mandi_Price": suggested_price,
                    "Hub_Location": pending["Hub_Location"],
                }

                st.session_state["inventory"] = pd.concat(
                    [working_df, pd.DataFrame([new_entry])], ignore_index=True
                )
                st.session_state["pending_entry"] = None

            st.success(
                f"AI Grading complete — Grade **{grade}** assigned. "
                f"Suggested ONDC listing price: **₹{suggested_price}/kg** "
                f"(mandi ref: ₹{mandi_price}/kg + 10%)."
            )
            st.rerun()

    st.divider()

    # ----------------------------------------------------------------------
    # Updated inventory table
    # ----------------------------------------------------------------------
    st.subheader("All Registered Produce")
    st.dataframe(st.session_state["inventory"], use_container_width=True)


