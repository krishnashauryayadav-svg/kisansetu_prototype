def simulate_ai_routing(item: pd.Series) -> None:
    """Runs a mock AI logistics routing simulation for the given catalogue item."""
    st.divider()
    st.subheader(f"🚚 AI Logistics Routing — {item['Crop_Type']} from {item['Farmer_Name']}")

    progress_bar = st.progress(0, text="Calculating optimal route...")
    stages = [
        (20, "Checking hub inventory..."),
        (45, "Matching nearest logistics partner..."),
        (70, "Calculating shortest route..."),
        (90, "Estimating delivery time..."),
        (100, "Route confirmed."),
    ]
    for pct, label in stages:
        time.sleep(0.3)
        progress_bar.progress(pct, text=label)

    # --- Mock routing outputs -------------------------------------------------
    logistics_partner = random.choice(LOGISTICS_PARTNERS)
    delivery_time = random.choice(["4-6 hours", "8-12 hours", "1 Day", "1-2 Days"])
    distance_km = round(random.uniform(35, 120), 1)

    st.success(
        f"✅ Order routed successfully!\n\n"
        f"**Logistics Partner:** {logistics_partner}  \n"
        f"**Estimated Delivery Time:** {delivery_time}  \n"
        f"**Approx. Route Distance:** {distance_km} km"
    )

    # --- Mock route map --------------------------------------------------------
    origin_name = item["Hub_Location"]
    origin_coords = HUB_COORDINATES.get(origin_name, (24.7, 84.9))  # fallback near Gaya
    dest_name, dest_coords = ONDC_BUYER_DESTINATION

    route_map = folium.Map(
        location=(
            (origin_coords[0] + dest_coords[0]) / 2,
            (origin_coords[1] + dest_coords[1]) / 2,
        ),
        zoom_start=8,
        tiles="cartodbpositron",
    )
    folium.Marker(
        origin_coords, tooltip=origin_name, popup=origin_name,
        icon=folium.Icon(color="green", icon="leaf"),
    ).add_to(route_map)
    folium.Marker(
        dest_coords, tooltip=dest_name, popup=dest_name,
        icon=folium.Icon(color="blue", icon="shopping-cart"),
    ).add_to(route_map)
    folium.PolyLine(
        [origin_coords, dest_coords], color="#16a34a", weight=4, dash_array="8",
    ).add_to(route_map)

    st.caption(f"Generic route preview: {origin_name} → {dest_name} (via {logistics_partner})")
    st_folium(route_map, use_container_width=True, height=380, key="routing_map")

    if st.button("Close routing panel"):
        st.session_state["routing_item_idx"] = None
        st.rerun()


def render_ondc_buyer_network(df: pd.DataFrame) -> None:
    st.title("ONDC Buyer Network")
    st.caption("Catalogue discovery & order flow for participating ONDC buyer apps")

    working_df = st.session_state.get("inventory", df)

    if working_df.empty:
        st.info("No inventory data loaded yet.")
        return

    # ------------------------------------------------------------------
    # Search & filters
    # ------------------------------------------------------------------
    search_col, hub_col, grade_col = st.columns([2, 1, 1])
    search_term = search_col.text_input("🔍 Search by crop or farmer name", "")
    hub_filter = hub_col.multiselect(
        "Hub Location", options=sorted(working_df["Hub_Location"].unique().tolist())
    )
    grade_filter = grade_col.multiselect(
        "Grade", options=sorted(working_df["Grade"].unique().tolist())
    )

    filtered = working_df.copy()
    if search_term:
        mask = (
            filtered["Crop_Type"].str.contains(search_term, case=False, na=False)
            | filtered["Farmer_Name"].str.contains(search_term, case=False, na=False)
        )
        filtered = filtered[mask]
    if hub_filter:
        filtered = filtered[filtered["Hub_Location"].isin(hub_filter)]
    if grade_filter:
        filtered = filtered[filtered["Grade"].isin(grade_filter)]

    st.subheader(f"🛒 Available Catalogue ({len(filtered)} listings)")

    if filtered.empty:
        st.warning("No listings match your search/filters.")
    else:
        # ------------------------------------------------------------------
        # E-commerce-style catalogue cards
        # ------------------------------------------------------------------
        for idx, row in filtered.iterrows():
            with st.container(border=True):
                c1, c2, c3, c4 = st.columns([3, 2, 2, 2])
                with c1:
                    st.markdown(f"**{row['Crop_Type']}**")
                    st.caption(f"Sold by {row['Farmer_Name']} · {row['Hub_Location']}")
                with c2:
                    st.metric("Grade", row["Grade"])
                with c3:
                    st.metric("Qty (kg)", f"{row['Quantity_KG']:,}")
                    st.caption(f"₹{row['Current_Mandi_Price']:.2f}/kg")
                with c4:
                    if st.button("🛍️ Buy & Route", key=f"buy_{idx}"):
                        st.session_state["routing_item_idx"] = idx

    # ------------------------------------------------------------------
    # If an item was selected, run the AI routing simulation for it
    # ------------------------------------------------------------------
    routing_idx = st.session_state["routing_item_idx"]
    if routing_idx is not None and routing_idx in working_df.index:
        simulate_ai_routing(working_df.loc[routing_idx])

